import { Router } from "express";
import { createWebsiteController, deleteWebsiteController, getWebsiteController, listWebsitesController, updateWebsiteController } from "../controllers/websiteController.js";
import { requireAuth } from "../middleware/requireAuth.js";
import { requireWebsiteOwnership } from "../middleware/requireOwnership.js";
import { validateWebsiteBody, validateWebsitePatch } from "../middleware/validateRequest.js";
import { asyncHandler } from "../utils/asyncHandler.js";
const router = Router();
router.use(asyncHandler(requireAuth));
router.get("/", asyncHandler(listWebsitesController));
router.get("/:id", asyncHandler(requireWebsiteOwnership), asyncHandler(getWebsiteController));
router.post("/", validateWebsiteBody, asyncHandler(createWebsiteController));
router.patch("/:id", asyncHandler(requireWebsiteOwnership), validateWebsitePatch, asyncHandler(updateWebsiteController));
router.delete("/:id", asyncHandler(requireWebsiteOwnership), asyncHandler(deleteWebsiteController));
export default router;
